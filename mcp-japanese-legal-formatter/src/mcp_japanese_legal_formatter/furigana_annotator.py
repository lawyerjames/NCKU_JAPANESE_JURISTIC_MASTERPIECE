_tokenizer_obj = None
_mode_c = None

def get_tokenizer():
    global _tokenizer_obj, _mode_c
    if _tokenizer_obj is None:
        _tokenizer_obj = dictionary.Dictionary().create()
        _mode_c = tokenizer.Tokenizer.SplitMode.C
    return _tokenizer_obj, _mode_c

def kata_to_hira(text: str) -> str:
    """Converts Katakana characters to Hiragana."""
    return "".join(
        chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in text
    )

