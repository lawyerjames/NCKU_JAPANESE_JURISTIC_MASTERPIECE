def annotate_token(surf: str, read: str = "", pitch_db: dict = None) -> str:
    """
    Annotates a token with furigana and pitch accent.
    If Kanji is present, wraps in <ruby>surf<rt>hira(pitch)</rt></ruby>.
    """
    active_db = PITCH_DB if pitch_db is None else pitch_db
    
    if surf in active_db:
        val = active_db[surf]
        hira, p = val if isinstance(val, tuple) else (val.split('(')[0], int(val.split('(')[1].rstrip(')')))
        return f"<ruby>{surf}<rt>{hira}({p})</rt></ruby>"
    
    # Check if Kanji exists
    has_kanji = any('一' <= c <= '鿿' for c in surf)
    if not has_kanji:
        return surf
        
    hira = kata_to_hira(read) if read else surf
    p = 0
    if surf.endswith('法') or surf.endswith('権') or surf.endswith('説') or surf.endswith('制') or surf.endswith('罪'):
        p = 0
    elif surf.endswith('者') or surf.endswith('性') or surf.endswith('化'):
        p = 0 if len(hira) <= 4 else 3
    elif surf.endswith('役') or surf.endswith('手'):
        p = 0
    elif surf.endswith('主義'):
        p = 4
    elif surf.endswith('責任'):
        p = 4 if len(hira) > 4 else 0
        
    return f"<ruby>{surf}<rt>{hira}({p})</rt></ruby>"

def format_japanese_text(text: str, custom_pitch_db: dict = None) -> str:
    """
    Formats Japanese legal text with:
    1. Bunsetsu boundaries tagged with <u>...</u> (red pause lines).
    2. Kanji annotated with <ruby>kanji<rt>reading(pitch)</rt></ruby>.
    3. Legal domain-specific pitch accents from PITCH_DB.
    """
    # Strip any existing ruby / u tags to avoid duplication
    text = re.sub(r'<rt>.*?</rt>', '', text)
    text = re.sub(r'</?ruby>', '', text)
    text = re.sub(r'</?u>', '', text)
    text = text.replace("\n", " ").strip()
    
    tok, mode = get_tokenizer()
    tokens = tok.tokenize(text, mode)
    
    chunks = []
    curr = []
    
    for t in tokens:
        surf = t.surface()
        read = t.reading_form()
        pos = t.part_of_speech()
        pos0 = pos[0]
        pos1 = pos[1] if len(pos) > 1 else ''
        
        annotated_item = annotate_token(surf, read, pitch_db=custom_pitch_db)
            
        starts_new_bunsetsu = False
        if curr:
            prev_surf, prev_read, prev_pos0, prev_pos1 = curr[-1]
            if pos0 in ['名詞', '動詞', '形容詞', '副詞', '接続詞', '感動詞', '連体詞', '形状詞']:
                if pos0 == '動詞' and prev_pos0 == '動詞' and surf in ['する', 'できる', 'いる', 'ある', 'なる', '得る', 'う', 'える', 'つく', 'され']:
                    starts_new_bunsetsu = False
                elif pos0 == '名詞' and prev_pos0 == '名詞':
                    starts_new_bunsetsu = False
                elif pos0 == '接尾辞' or prev_pos0 == '接頭辞':
                    starts_new_bunsetsu = False
                elif prev_pos0 == '接頭辞':
                    starts_new_bunsetsu = False
                elif pos1 == '非自立可能':
                    starts_new_bunsetsu = False
                else:
                    starts_new_bunsetsu = True
                    
        if starts_new_bunsetsu:
            chunk_str = "".join([item for item, _, _, _ in curr])
            chunks.append(f"<u>{chunk_str}</u>")
            curr = [(annotated_item, read, pos0, pos1)]
        else:
            curr.append((annotated_item, read, pos0, pos1))
            
    if curr:
        chunk_str = "".join([item for item, _, _, _ in curr])
        chunks.append(f"<u>{chunk_str}</u>")
        
    res = " ".join(chunks)
    res = re.sub(r'\s+', ' ', res)
    return res

def sanitize_furigana_ruby(text: str) -> str:
    """
    Sanitizes ruby tags to ensure furigana is placed ONLY over Kanji characters,
    stripping trailing hiragana, romaji, and syntax errors.
    """
    text = re.sub(r'<rt>([^<]*?)([a-zA-Z]+)([^<]*?)</rt>', r'<rt></rt>', text)
    
    ruby_open = len(re.findall(r'<ruby>', text))
    ruby_close = len(re.findall(r'</ruby>', text))
    if ruby_open != ruby_close:
        text = text.replace('<ruby>', '').replace('</ruby>', '')
    return text

def audit_annotations(html_text: str) -> dict:
    """
    Audits ruby, rt, and u tags balance in an HTML text.
    Returns status and tag metrics.
    """
    ruby_open = len(re.findall(r'<ruby>', html_text))
    ruby_close = len(re.findall(r'</ruby>', html_text))
    rt_open = len(re.findall(r'<rt>', html_text))
    rt_close = len(re.findall(r'</rt>', html_text))
    u_open = len(re.findall(r'<u>', html_text))
    u_close = len(re.findall(r'</u>', html_text))
    romaji_in_rt = [rt for rt in re.findall(r'<rt>(.*?)</rt>', html_text) if re.search(r'[a-zA-Z]', rt)]
    
    is_valid = (ruby_open == ruby_close) and (rt_open == rt_close) and (u_open == u_close) and (len(romaji_in_rt) == 0)
    
    return {
        "is_valid": is_valid,
        "ruby_count": ruby_open,
        "rt_count": rt_open,
        "u_count": u_open,
        "romaji_errors": len(romaji_in_rt)
    }
